//! Embeds the desktop payload into the executable and prepares Tauri.
//!
//! A portable "green" build has to work from a single file with nothing beside
//! it, so every byte the app needs at runtime - the Web UI, the default
//! configuration and the response filters - is compiled in here instead of
//! being read from an install directory. At startup `materialize` writes them
//! into the runtime directory so the shared core, which serves the UI straight
//! off disk, finds exactly the layout it expects.
//!
//! Run cargo from the workspace root; asset paths are resolved relative to this
//! manifest so the build does not depend on the current directory.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    tauri_build::build();
    embed_assets();
}

/// `(runtime-relative path, source file, owned by the app)`
///
/// `owned` assets are rewritten whenever their content differs: they are UI code
/// and filters, so a stale copy would be a bug. Everything else is seeded only
/// when missing, because a user who edits `config.json` means it.
type Seed = (String, PathBuf, bool);

fn embed_assets() {
    let repo = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("desktop/ must live inside the workspace")
        .to_path_buf();

    let mut seeds: Vec<Seed> = Vec::new();
    collect(&repo.join("ui"), "web", true, &mut seeds);
    collect(&repo.join("runtime").join("config"), "config", false, &mut seeds);
    collect(&repo.join("runtime").join("filters"), "filters", true, &mut seeds);
    seeds.sort_by(|a, b| a.0.cmp(&b.0));

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let mut generated = String::from(
        "// @generated by desktop/build.rs - do not edit.\n\
         //\n\
         // Asset tables shared by the startup materialiser. `owned` marks the\n\
         // files the application may overwrite; the rest are user-editable seeds.\n",
    );
    let _ = writeln!(
        generated,
        "pub static EMBEDDED_ASSETS: &[(&str, &[u8])] = &["
    );
    let mut owned = String::new();
    for (rel, abs, is_owned) in &seeds {
        println!("cargo:rerun-if-changed={}", abs.display());
        if *is_owned {
            let _ = writeln!(owned, "    {:?},", rel);
        }
        // `include_bytes!` wants a literal; forward slashes keep it readable and
        // work identically on every host Cargo might generate from.
        let _ = writeln!(
            generated,
            "    ({:?}, include_bytes!({:?})),",
            rel,
            abs.to_string_lossy().replace('\\', "/")
        );
    }

    let _ = writeln!(generated, "];\n\npub static OWNED_ASSETS: &[&str] = &[");
    generated.push_str(&owned);
    generated.push_str("];\n");

    fs::write(out_dir.join("embedded_assets.rs"), generated).expect("write embedded_assets.rs");
}

fn collect(dir: &Path, prefix: &str, owned: bool, out: &mut Vec<Seed>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for entry in entries {
        let entry = entry.expect("dir entry");
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if entry
            .file_type()
            .map(|t| t.is_dir())
            .unwrap_or(false)
        {
            collect(&path, &format!("{prefix}/{name}"), owned, out);
        } else {
            out.push((format!("{prefix}/{name}"), path, owned));
        }
    }
}
